-- Composition d'emballage par conditionnement — remplace à terme l'hypothèse
-- figée sachet=couvercle=scellé (LignePlanDetail.getTotalSachets/Couvercles/
-- Scelles(), toutes trois égales à getTotalUnites()). Ces méthodes ne sont
-- PAS retirées par cette migration : les deux systèmes coexistent jusqu'au
-- retrait prévu, une fois PlanificationProductionService basculé dessus.

ALTER TABLE conditionnements ADD COLUMN type_emballage VARCHAR(20);
ALTER TABLE conditionnements ADD CONSTRAINT conditionnements_type_emballage_check
    CHECK (type_emballage IS NULL OR type_emballage = ANY (ARRAY[
        'SACHET', 'COUVERCLE', 'SCELLE', 'CARTON', 'SEAU', 'GAINE', 'ETUI'
    ]));

CREATE TABLE composants_emballage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conditionnement_id VARCHAR(36) NOT NULL REFERENCES conditionnements(id) ON DELETE CASCADE,
    type_composant VARCHAR(20) NOT NULL,
    quantite_composant INTEGER NOT NULL,
    quantite_unites_produites INTEGER NOT NULL,
    CONSTRAINT composants_emballage_type_check
        CHECK (type_composant = ANY (ARRAY['SACHET', 'COUVERCLE', 'SCELLE', 'CARTON', 'SEAU', 'GAINE', 'ETUI'])),
    CONSTRAINT composants_emballage_quantite_composant_check CHECK (quantite_composant > 0),
    CONSTRAINT composants_emballage_quantite_unites_check CHECK (quantite_unites_produites > 0)
);

-- ═══════════════════════════════════════════════════════════════════════════
-- Reprise du comportement actuel (1 sachet = 1 couvercle = 1 scellé par
-- unité produite) comme données initiales, pour les seuls produits dont le
-- conditionnement réel est un sachet (gamme = 'Sachets' dans le catalogue
-- web, codes TBS-SAC-*) — afin de ne rien changer à leur calcul le jour où
-- PlanificationProductionService utilisera cette composition à la place de
-- l'hypothèse figée.
--
-- Volontairement NON étendu ici aux étuis (TBS-ETU-*, ING-CHP-001), seaux
-- (RCP-*, TCH-*, BVT-*) ni aux gammes Minis/Moyens/Grands (TAG-*) : leur
-- conditionnement réel n'est pas forcément un sachet, et l'ancien code ne
-- distinguait de toute façon aucun type — leur assigner une composition
-- SACHET par défaut serait une hypothèse nouvelle, pas une reprise de
-- l'existant. Ils restent donc sans type ni composition (état valide) en
-- attendant une donnée réelle.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE conditionnements SET type_emballage = 'SACHET'
WHERE code_produit IN (
    'TBS-SAC-001', 'TBS-SAC-002', 'TBS-SAC-003', 'TBS-SAC-004', 'TBS-SAC-005',
    'TBS-SAC-006', 'TBS-SAC-007', 'TBS-SAC-008', 'TBS-SAC-009', 'TBS-SAC-010'
) AND niveau = 'UNITE_BASE';

INSERT INTO composants_emballage (conditionnement_id, type_composant, quantite_composant, quantite_unites_produites)
SELECT c.id, comp.type, 1, 1
FROM conditionnements c
JOIN (VALUES ('SACHET'), ('COUVERCLE'), ('SCELLE')) AS comp(type) ON true
WHERE c.code_produit IN (
    'TBS-SAC-001', 'TBS-SAC-002', 'TBS-SAC-003', 'TBS-SAC-004', 'TBS-SAC-005',
    'TBS-SAC-006', 'TBS-SAC-007', 'TBS-SAC-008', 'TBS-SAC-009', 'TBS-SAC-010'
) AND c.niveau = 'UNITE_BASE';
