-- système figé sont converties en lignes génériques équivalentes, pour ne
-- perdre aucun PPH déjà généré. Les lignes sans matière/composant concerné
-- (valeur à 0) ne créent pas de ligne générique — 0 kg de maïs pour un
-- produit qui n'en a jamais eu n'est pas une donnée à reprendre.
-- ═══════════════════════════════════════════════════════════════════════════

