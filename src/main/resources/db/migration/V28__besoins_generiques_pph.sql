-- Généralisation des besoins de production (matières premières et emballage)
-- sur lignes_plan_detail / repartition_pph_jours — remplace les colonnes
-- figées poudre_mais_kg/poudre_soja_kg/poudre_arachide_kg (RecetteBouillie,
-- retirée) et sachets_prevus/couvercles_prevus/scelles_prevus (hypothèse
-- 1:1:1, retirée) par une structure générique : une ligne par matière
-- première / par composant d'emballage réellement concerné, au lieu de
-- colonnes fixes à trois matières et trois composants.

CREATE TABLE besoins_matiere_premiere_ligne (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ligne_plan_detail_id BIGINT NOT NULL REFERENCES lignes_plan_detail(id) ON DELETE CASCADE,
    matiere_premiere VARCHAR(100) NOT NULL,
    quantite_kg NUMERIC(12,2) NOT NULL
);

CREATE TABLE besoins_emballage_ligne (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ligne_plan_detail_id BIGINT NOT NULL REFERENCES lignes_plan_detail(id) ON DELETE CASCADE,
    type_composant VARCHAR(20) NOT NULL,
    quantite BIGINT NOT NULL
);

CREATE TABLE besoins_matiere_premiere_jour (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repartition_jour_id BIGINT NOT NULL REFERENCES repartition_pph_jours(id) ON DELETE CASCADE,
    matiere_premiere VARCHAR(100) NOT NULL,
    quantite_kg NUMERIC(12,2) NOT NULL
);

CREATE TABLE besoins_emballage_jour (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repartition_jour_id BIGINT NOT NULL REFERENCES repartition_pph_jours(id) ON DELETE CASCADE,
    type_composant VARCHAR(20) NOT NULL,
    quantite BIGINT NOT NULL
);

ALTER TABLE lignes_plan_detail ADD COLUMN formule_manquante BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE lignes_plan_detail ADD COLUMN composition_emballage_manquante BOOLEAN NOT NULL DEFAULT FALSE;

