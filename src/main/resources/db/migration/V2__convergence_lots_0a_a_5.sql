-- =============================================================================
-- V2 — Convergence du schéma avec le code (lots 0A à 5), et reprise de la
--      dérive antérieure qui empêchait la validation Hibernate.
--
-- Contrairement à V1, cette migration EST exécutée sur les bases existantes.
-- Elle n'effectue aucune suppression : les colonnes rendues obsolètes par des
-- renommages antérieurs sont conservées, leur contenu étant recopié dans les
-- nouvelles. Rien n'est perdu, et un retour arrière reste possible sans
-- restauration de sauvegarde.
--
-- Trois ensembles distincts :
--   1. Séquences de numérotation métier (lot 0A)
--   2. Objets introduits par les lots 0A à 5
--   3. Dérive antérieure à la mission, bloquante pour ddl-auto=validate
-- =============================================================================


-- =============================================================================
-- 1. SÉQUENCES DE NUMÉROTATION MÉTIER
-- =============================================================================
-- Aucune entité JPA ne les déclare : Hibernate ne les aurait jamais créées.
-- Elles étaient jusqu'ici produites au démarrage par GenerateurNumeroMetier ;
-- leur création rejoint ici le schéma versionné, où elle est à sa place.
--
-- Un nextval n'est jamais annulé par un rollback : la numérotation peut
-- présenter des trous, jamais de doublon. C'est la propriété recherchée.

CREATE SEQUENCE IF NOT EXISTS seq_numero_vente        START WITH 1 INCREMENT BY 1 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS seq_numero_precommande  START WITH 1 INCREMENT BY 1 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS seq_numero_retour       START WITH 1 INCREMENT BY 1 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS seq_numero_non_marchand START WITH 1 INCREMENT BY 1 NO CYCLE;
CREATE SEQUENCE IF NOT EXISTS seq_numero_mouvement    START WITH 1 INCREMENT BY 1 NO CYCLE;


-- =============================================================================
-- 2. OBJETS INTRODUITS PAR LES LOTS 0A À 5
-- =============================================================================

-- ── 2.1 Règles métier datées (lot 1) ─────────────────────────────────────────
-- Quatre agrégats bâtis sur le même principe : une période de validité non
-- chevauchante, si bien qu'une date donnée désigne toujours exactement une
-- version. date_fin nulle signale la version courante. Aucune valeur métier
-- n'est insérée ici : les règles historiques restent portées par le code tant
-- qu'aucune version n'a été enregistrée, ce qui évite de figer en base des
-- seuils que personne n'a décidés.

CREATE TABLE IF NOT EXISTS baremes_prime (
    id                            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                     varchar(60)  NOT NULL UNIQUE,
    taux_global_minimum_pourcent  double precision NOT NULL,
    taux_gamme_minimum_pourcent   double precision NOT NULL,
    montant_par_gammefcfa         double precision NOT NULL,
    montant_maximumfcfa           double precision NOT NULL,
    date_debut                    date         NOT NULL,
    date_fin                      date,
    matricule_auteur              varchar(40)  NOT NULL,
    motif                         varchar(500),
    date_creation                 timestamp(6) NOT NULL,
    version                       bigint
);

CREATE TABLE IF NOT EXISTS parametrages_caisse (
    id                                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                         varchar(60)  NOT NULL UNIQUE,
    seuil_securisationfcfa            double precision NOT NULL,
    seuil_alerte_rouge_versementfcfa  double precision NOT NULL,
    date_debut                        date         NOT NULL,
    date_fin                          date,
    matricule_auteur                  varchar(40)  NOT NULL,
    motif                             varchar(500),
    date_creation                     timestamp(6) NOT NULL,
    version                           bigint
);

CREATE TABLE IF NOT EXISTS parametrages_objectif (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference            varchar(60)  NOT NULL UNIQUE,
    nombre_jours_ouvres  integer      NOT NULL,
    date_debut           date         NOT NULL,
    date_fin             date,
    matricule_auteur     varchar(40)  NOT NULL,
    motif                varchar(500),
    date_creation        timestamp(6) NOT NULL,
    version              bigint
);

CREATE TABLE IF NOT EXISTS regles_avarie (
    id                                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                         varchar(60)  NOT NULL UNIQUE,
    quantite_seuil_photo_obligatoire  integer      NOT NULL,
    date_debut                        date         NOT NULL,
    date_fin                          date,
    matricule_auteur                  varchar(40)  NOT NULL,
    motif                             varchar(500),
    date_creation                     timestamp(6) NOT NULL,
    version                           bigint
);

-- ── 2.2 Journal des révisions d'objectif (lot 5) ─────────────────────────────
-- Conserve la valeur remplacée lors d'une révision. Sans ce journal, abaisser
-- un objectif en fin de semaine rendait éligible à la prime un commercial qui
-- ne l'était pas, sans qu'aucune trace ne subsiste.

CREATE TABLE IF NOT EXISTS objectifs_revisions (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objectif_commercial_id      bigint       NOT NULL,
    objectif_global_avant_fcfa  double precision NOT NULL,
    objectif_global_apres_fcfa  double precision NOT NULL,
    matricule_auteur            varchar(20)  NOT NULL,
    motif                       varchar(500),
    date_revision               timestamp(6) NOT NULL,
    CONSTRAINT fk_revision_objectif_commercial
        FOREIGN KEY (objectif_commercial_id) REFERENCES objectifs_commerciaux (id)
);

CREATE INDEX IF NOT EXISTS idx_revision_objectif
    ON objectifs_revisions (objectif_commercial_id);

CREATE TABLE IF NOT EXISTS objectifs_revisions_gammes (
    revision_id    bigint       NOT NULL,
    gamme          varchar(255) NOT NULL,
    objectif_fcfa  double precision,
    PRIMARY KEY (revision_id, gamme),
    CONSTRAINT fk_revision_gamme
        FOREIGN KEY (revision_id) REFERENCES objectifs_revisions (id)
);

-- ── 2.3 Arbitrage des précommandes (lot 0A) ──────────────────────────────────
-- La quantité demandée et la quantité arbitrée coexistent désormais : arbitrer
-- 100 en 70 ne doit jamais effacer le 100 initialement demandé.

ALTER TABLE precommandes ADD COLUMN IF NOT EXISTS matricule_arbitre varchar(255);
ALTER TABLE precommandes ADD COLUMN IF NOT EXISTS date_arbitrage    timestamp(6);
ALTER TABLE precommandes ADD COLUMN IF NOT EXISTS motif_arbitrage   varchar(500);

-- ── 2.4 Barème appliqué à une prime (lot 1) ──────────────────────────────────
-- Rattache chaque prime au barème en vigueur à sa date. Les primes antérieures
-- restent sans référence : elles ont été calculées avant l'introduction du
-- barème administrable, et leur en attribuer un rétroactivement laisserait
-- croire à une traçabilité qui n'existe pas.

ALTER TABLE primes_commerciales ADD COLUMN IF NOT EXISTS reference_bareme varchar(60);

-- ── 2.5 Constat d'invendus en deux temps (lot 3) ─────────────────────────────
-- Le commercial déclare, le gestionnaire compte. Aucun stock ne bouge : les
-- invendus restent au camion.

ALTER TABLE bons_retour   ADD COLUMN IF NOT EXISTS statut           varchar(20);
ALTER TABLE bons_retour   ADD COLUMN IF NOT EXISTS date_comptage    timestamp(6);
ALTER TABLE lignes_retour ADD COLUMN IF NOT EXISTS quantite_comptee bigint;

-- Le gestionnaire n'est connu qu'au comptage : la contrainte NOT NULL empêchait
-- l'enregistrement d'une déclaration.
ALTER TABLE bons_retour ALTER COLUMN matricule_gestionnaire DROP NOT NULL;

-- Les constats antérieurs ont été saisis d'un seul tenant par le gestionnaire,
-- donc déjà vérifiés. Les laisser sans statut les ferait apparaître en attente
-- de comptage. Leur quantité comptée demeure inconnue et le reste : elle n'est
-- pas fabriquée à partir de la quantité déclarée.
UPDATE bons_retour SET statut = 'COMPTE' WHERE statut IS NULL;


-- =============================================================================
-- 3. DÉRIVE ANTÉRIEURE À LA MISSION
-- =============================================================================
-- Ces écarts entre le code et la base préexistaient au chantier de convergence.
-- Ils sont repris ici parce qu'ils empêcheraient le passage à
-- ddl-auto=validate, et donc la reprise du schéma par Flyway.

-- ── 3.1 Détail du conditionnement ────────────────────────────────────────────
-- Le catalogue ne comporte que deux niveaux : UNITE_BASE (facteur 1) et CARTON
-- (facteur = nombre d'unités contenues). Le nombre d'unités est donc exactement
-- le facteur de conversion, et l'unité est le libellé du conditionnement de
-- base du même produit. Les deux valeurs sont dérivées des données existantes,
-- aucune n'est inventée.

ALTER TABLE conditionnements ADD COLUMN IF NOT EXISTS nombre_unites         integer;
ALTER TABLE conditionnements ADD COLUMN IF NOT EXISTS unite_conditionnement varchar(30);

UPDATE conditionnements
   SET nombre_unites = facteur_conversion_vers_base
 WHERE nombre_unites IS NULL;

UPDATE conditionnements c
   SET unite_conditionnement = COALESCE(
        (SELECT lower(b.libelle)
           FROM conditionnements b
          WHERE b.code_produit = c.code_produit
            AND b.niveau = 'UNITE_BASE'
          LIMIT 1),
        'unite')
 WHERE c.unite_conditionnement IS NULL;

ALTER TABLE conditionnements ALTER COLUMN nombre_unites         SET NOT NULL;
ALTER TABLE conditionnements ALTER COLUMN unite_conditionnement SET NOT NULL;

-- ── 3.2 Séance de dosage en pause ────────────────────────────────────────────
-- Une séance déjà enregistrée n'est pas en pause : false est ici un constat,
-- pas une valeur par défaut arbitraire.

ALTER TABLE sessions_dosage ADD COLUMN IF NOT EXISTS en_pause boolean;
UPDATE sessions_dosage SET en_pause = false WHERE en_pause IS NULL;
ALTER TABLE sessions_dosage ALTER COLUMN en_pause SET NOT NULL;

-- ── 3.3 Lots de produits finis — renommage antérieur ─────────────────────────
-- Le code interroge product_sku, product_name, declared_quantity_kg et
-- equivalent_units ; la base porte encore code_produit, designation_produit,
-- quantite_kg et nb_cartons. Les anciennes colonnes sont CONSERVÉES et leur
-- contenu recopié : aucune donnée n'est détruite par cette migration.
--
-- La correspondance nb_cartons → equivalent_units est un simple renommage :
-- « carton » n'était qu'un des conditionnements possibles (carton, étui, gaine,
-- sachet, seau), et la colonne comptait en réalité des unités de conditionnement,
-- quel qu'il soit. C'est bien ce que désigne equivalent_units, que le nom précédent
-- restreignait à tort. La conversion vers le stock, elle, ne passe pas par cette
-- colonne : elle est calculée à partir de conditioning_type et conditioning_qty
-- (cf. ProductionBatchService.convertirConditionnementEnBase). Aucune règle métier
-- n'est donc déduite ici.

ALTER TABLE lots_produits_finis ADD COLUMN IF NOT EXISTS product_sku          varchar(50);
ALTER TABLE lots_produits_finis ADD COLUMN IF NOT EXISTS product_name         varchar(200);
ALTER TABLE lots_produits_finis ADD COLUMN IF NOT EXISTS declared_quantity_kg double precision;
ALTER TABLE lots_produits_finis ADD COLUMN IF NOT EXISTS equivalent_units     integer;

UPDATE lots_produits_finis
   SET product_sku          = COALESCE(product_sku, code_produit),
       product_name         = COALESCE(product_name, designation_produit),
       declared_quantity_kg = COALESCE(declared_quantity_kg, quantite_kg),
       equivalent_units     = COALESCE(equivalent_units, nb_cartons);

ALTER TABLE lots_produits_finis ALTER COLUMN product_sku          SET NOT NULL;
ALTER TABLE lots_produits_finis ALTER COLUMN product_name         SET NOT NULL;
ALTER TABLE lots_produits_finis ALTER COLUMN declared_quantity_kg SET NOT NULL;
ALTER TABLE lots_produits_finis ALTER COLUMN equivalent_units     SET NOT NULL;
