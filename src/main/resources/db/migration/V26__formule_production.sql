-- 2) Peanut Porridge (40 Maïs / 1 Soja / 9 Arachide) — désignation contenant « ARACHIDES ».
INSERT INTO lignes_formule (formule_id, matiere_premiere, proportion_kg)
SELECT f.id, m.nom, m.qte
FROM formules_production f
JOIN (VALUES ('Maïs', 40), ('Soja', 1), ('Arachide', 9)) AS m(nom, qte) ON true
WHERE f.code_produit IN ('TBS-SAC-001', 'TBS-SAC-006', 'TBS-ETU-001', 'TBS-ETU-006');

-- 3) Simple Porridge (40 Maïs / 9 Soja / 1 Arachide) — tous les autres produits Bouillie de Soja.
INSERT INTO lignes_formule (formule_id, matiere_premiere, proportion_kg)
SELECT f.id, m.nom, m.qte
FROM formules_production f
JOIN (VALUES ('Maïs', 40), ('Soja', 9), ('Arachide', 1)) AS m(nom, qte) ON true
WHERE f.code_produit NOT IN ('TBS-SAC-001', 'TBS-SAC-006', 'TBS-ETU-001', 'TBS-ETU-006');
