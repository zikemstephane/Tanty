-- Formule de production par produit — remplace à terme RecetteBouillie
-- (enum à deux variantes figées). RecetteBouillie n'est PAS retirée par
-- cette migration : les deux systèmes coexistent jusqu'au retrait prévu du
-- code de l'enum (bloc distinct), une fois PlanificationProductionService
-- basculé sur FormuleProduction.

CREATE TABLE formules_production (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_produit VARCHAR(50) NOT NULL,
    base_kg NUMERIC(12,3) NOT NULL,
    date_creation TIMESTAMP(6) NOT NULL,
    date_modification TIMESTAMP(6),
    version BIGINT,
    CONSTRAINT formules_production_code_produit_key UNIQUE (code_produit),
    CONSTRAINT formules_production_base_kg_check CHECK (base_kg > 0)
);

CREATE TABLE lignes_formule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formule_id BIGINT NOT NULL REFERENCES formules_production(id) ON DELETE CASCADE,
    matiere_premiere VARCHAR(100) NOT NULL,
    proportion_kg NUMERIC(12,3) NOT NULL,
    CONSTRAINT lignes_formule_proportion_kg_check CHECK (proportion_kg >= 0)
);

-- ═══════════════════════════════════════════════════════════════════════════
-- Reprise des deux recettes actuelles de RecetteBouillie.java, assignées
-- explicitement par code produit — même règle que RecetteBouillie.depuisDesignation()
-- (« ARACHIDE » dans la désignation ⇒ Peanut Porridge, sinon Simple Porridge),
-- appliquée aux seuls produits réellement de catégorie TANTY_BOUILLIE_DE_SOJA.
--
-- BVT-001 et BVT-002 (Babyvita) sont volontairement EXCLUS de cette reprise :
-- leur catégorie TANTY_BOUILLIE_DE_SOJA n'est elle-même qu'un rattachement
-- provisoire (cf. CatalogueSeeder), pas une confirmation qu'il s'agit d'une
-- bouillie au même titre que les Reine/Tanty/Costard. Ils restent donc sans
-- formule (état valide) en attendant une décision explicite.
-- ═══════════════════════════════════════════════════════════════════════════

