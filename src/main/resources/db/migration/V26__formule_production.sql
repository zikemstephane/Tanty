    ('TBS-SAC-006'), ('TBS-SAC-007'), ('TBS-SAC-008'), ('TBS-SAC-009'), ('TBS-SAC-010'),
    ('TBS-ETU-001'), ('TBS-ETU-002'), ('TBS-ETU-003'), ('TBS-ETU-004'), ('TBS-ETU-005'),
    ('TBS-ETU-006'), ('TBS-ETU-007'), ('TBS-ETU-008'), ('TBS-ETU-009'), ('TBS-ETU-010'),
    ('RCP-1L-001'), ('RCP-1L-002'), ('RCP-1L-003'), ('RCP-1L-004'),
    ('RCP-2L-001'), ('RCP-2L-002'), ('RCP-2L-003'), ('RCP-2L-004'),
